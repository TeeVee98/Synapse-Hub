def sync_all(check_only: bool = False) -> int:
    """Synchronizes schemas and reports any drift."""
    if not os.path.isfile(SCHEMA_PATH):
        print(f"❌ [SCHEMA SYNC ERROR] Schema definition not found at: {SCHEMA_PATH}")
        return 1

    schema = load_json(SCHEMA_PATH)
    config = load_json(CONFIG_PATH) if os.path.isfile(CONFIG_PATH) else {}

    # 1. Conformance check
    errors = validate_config_conformance(config, schema)
    if errors:
        print("❌ [SCHEMA CONFORMANCE DRIFT DETECTED]:")
        for err in errors:
            print(f"   • {err}")
        return 1

    py_code = generate_python_models(schema)
    ts_code = generate_typescript_declarations(schema)

    if check_only:
        drift = False
        if not os.path.isfile(PY_MODEL_FILE):
            print(f"❌ [DRIFT] Python model file missing: {PY_MODEL_FILE}")
            drift = True
        else:
            with open(PY_MODEL_FILE, "r", encoding="utf-8") as f:
                if f.read().strip() != py_code.strip():
                    print(f"❌ [DRIFT] Python model drift in {PY_MODEL_FILE}")
                    drift = True

        if not os.path.isfile(TS_TYPES_FILE):
            print(f"❌ [DRIFT] TypeScript definition missing: {TS_TYPES_FILE}")
            drift = True
        else:
            with open(TS_TYPES_FILE, "r", encoding="utf-8") as f:
                if f.read().strip() != ts_code.strip():
                    print(f"❌ [DRIFT] TypeScript definition drift in {TS_TYPES_FILE}")
                    drift = True

        if drift:
            print("\n🚨 Run 'python tools/core/sync_schemas.py' to regenerate synchronized types.")
            return 1
        print("✅ [SCHEMA PASS] Zero schema drift across Python and TypeScript models.")
        return 0

    # Write files
    os.makedirs(PY_MODELS_DIR, exist_ok=True)
    with open(PY_INIT_FILE, "w", encoding="utf-8") as f:
        f.write('''# SPDX-FileCopyrightText: © 2026 Thế Vị (@TeeVee98) <https://github.com/TeeVee98/Synapse-Hub>
# SPDX-License-Identifier: MIT

"""
Synapse Hub — Config Models Package (tools.core.models)
"""
from tools.core.models.config_model import SynapseConfig, QualityGateConfig

__all__ = ["SynapseConfig", "QualityGateConfig"]
''')

    with open(PY_MODEL_FILE, "w", encoding="utf-8") as f:
        f.write(py_code)

    os.makedirs(os.path.dirname(TS_TYPES_FILE), exist_ok=True)
    with open(TS_TYPES_FILE, "w", encoding="utf-8") as f:
        f.write(ts_code)

    print("======================================================================")
    print("✅ [SCHEMA SYNC COMPLETE] Generated zero-drift cross-platform types:")
    print(f"   • Python Models     : {PY_MODEL_FILE}")
    print(f"   • TypeScript Types  : {TS_TYPES_FILE}")
    print(f"   • Config Conformance: {CONFIG_PATH} (100% PASS)")
    print("======================================================================")
    return 0


def main():
    parser = argparse.ArgumentParser(description="Synchronize JSON Schemas to Python and TypeScript models")
    parser.add_argument("--check", action="store_true", help="Check for drift without writing files")
    args = parser.parse_args()
    return sync_all(check_only=args.check)


if __name__ == "__main__":
    sys.exit(main())
