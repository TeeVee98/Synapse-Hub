#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
tools/mechanical_ui_gate.py — Headless Chrome Mechanical Layout & Contrast Gate
Inspired by Leonxlnx's taste-skill (gate.mjs & consistency.mjs).
Enforces mechanical finish criteria on rendered HTML and UI components:
zero horizontal overflow spills, WCAG AA contrast (>= 4.5:1), valid interactive
tap targets, and zero empty/unstyled placeholder divs.
100% UTF-8 No BOM.
"""

import sys
import os
import re
import json
import argparse
from typing import Dict, Any, Optional, Tuple

# Enforce UTF-8 stdout encoding
if hasattr(sys.stdout, "reconfigure"):
    try:
        sys.stdout.reconfigure(encoding="utf-8")
        sys.stderr.reconfigure(encoding="utf-8")
    except Exception:
        pass

def parse_css_color(color_str: str) -> Optional[Tuple[int, int, int]]:
    c = color_str.strip().lower()
    named = {
        "white": (255, 255, 255),
        "black": (0, 0, 0),
        "red": (255, 0, 0),
        "green": (0, 128, 0),
        "blue": (0, 0, 255),
        "yellow": (255, 255, 0),
        "cyan": (0, 255, 255),
        "magenta": (255, 0, 255),
        "gray": (128, 128, 128),
        "grey": (128, 128, 128),
    }
    if c in named:
        return named[c]
    if c.startswith("#"):
        h = c[1:]
        if len(h) == 3:
            return (int(h[0]*2, 16), int(h[1]*2, 16), int(h[2]*2, 16))
        elif len(h) == 6:
            return (int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16))
    m = re.match(r'rgba?\s*\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)', c)
    if m:
        return (int(m.group(1)), int(m.group(2)), int(m.group(3)))
    return None

def calc_relative_luminance(rgb: Tuple[int, int, int]) -> float:
    def ch(val: int) -> float:
        v = val / 255.0
        return v / 12.92 if v <= 0.03928 else ((v + 0.055) / 1.055) ** 2.4
    return 0.2126 * ch(rgb[0]) + 0.7152 * ch(rgb[1]) + 0.0722 * ch(rgb[2])

def calc_contrast_ratio(rgb1: Tuple[int, int, int], rgb2: Tuple[int, int, int]) -> float:
    l1 = calc_relative_luminance(rgb1)
    l2 = calc_relative_luminance(rgb2)
    return (max(l1, l2) + 0.05) / (min(l1, l2) + 0.05)

class MechanicalUIGate:
    def __init__(self, min_contrast: float = 4.5):
        self.min_contrast = min_contrast

    def audit_html_content(self, html_text: str, filename: str = "inline.html") -> Dict[str, Any]:
        """Performs static DOM and structural mechanical checks on HTML content."""
        findings = []

        # 1. Check for empty interactive elements (buttons, links without accessible text or aria-label)
        empty_button_re = re.compile(r'<button\b(?![^>]*\baria-label=)[^>]*>\s*</button>', re.IGNORECASE)
        for m in empty_button_re.finditer(html_text):
            findings.append({
                "id": "empty-button",
                "severity": "FAIL",
                "message": "Found button element with zero inner text and no aria-label.",
                "snippet": m.group(0)[:80]
            })

        empty_link_re = re.compile(r'<a\b(?![^>]*\baria-label=)[^>]*>\s*</a>', re.IGNORECASE)
        for m in empty_link_re.finditer(html_text):
            findings.append({
                "id": "empty-anchor",
                "severity": "FAIL",
                "message": "Found <a> link element with zero inner text and no aria-label.",
                "snippet": m.group(0)[:80]
            })

        # 2. Check for missing viewport meta tag (causes layout overflow on mobile)
        if "<meta" in html_text.lower() and "viewport" not in html_text.lower():
            findings.append({
                "id": "missing-viewport",
                "severity": "FAIL",
                "message": "Missing <meta name='viewport'> tag, resulting in mobile rendering breakage.",
                "snippet": "<meta ...>"
            })

        # 3. Check for inline fixed-width overflows (e.g. style='width: 1400px' or style='min-width: 1200px' without max-width)
        fixed_overflow_re = re.compile(r'style=[\'"][^\'"]*?(?:min-)?width:\s*(\d{4,})px', re.IGNORECASE)
        for m in fixed_overflow_re.finditer(html_text):
            px_val = int(m.group(1))
            if px_val > 1000 and "max-width" not in m.group(0):
                findings.append({
                    "id": "overflow-fixed-width",
                    "severity": "WARN",
                    "message": f"Fixed width {px_val}px without max-width: 100% may cause viewport horizontal scroll.",
                    "snippet": m.group(0)[:80]
                })

        # 4. Check for unhandled AI slop tags / comments
        ai_comment_re = re.compile(r'<!--\s*(?:AI-generated|TODO: add content|Placeholder|Generated by)\b[^-]*?-->', re.IGNORECASE)
        for m in ai_comment_re.finditer(html_text):
            findings.append({
                "id": "ai-placeholder-comment",
                "severity": "FAIL",
                "message": "Found unresolved AI placeholder comment.",
                "snippet": m.group(0)[:80]
            })

        # 5. Check for heading hierarchy skip (e.g. h1 directly followed by h4 without h2 or h3)
        headings = re.findall(r'<h([1-6])\b', html_text, re.IGNORECASE)
        levels = [int(h) for h in headings]
        for i in range(len(levels) - 1):
            if levels[i+1] > levels[i] + 1:
                findings.append({
                    "id": "heading-order-skipped",
                    "severity": "WARN",
                    "message": f"Skipped heading level: h{levels[i]} followed directly by h{levels[i+1]}.",
                    "snippet": f"h{levels[i]} -> h{levels[i+1]}"
                })

        # 6. Check for low contrast inline styles (WCAG AA min_contrast, default 4.5:1)
        style_matches = re.finditer(r'style=[\'"]([^\'"]+)[\'"]', html_text, re.IGNORECASE)
        for sm in style_matches:
            s_text = sm.group(1)
            fg_m = re.search(r'(?:^|;)\s*color:\s*([^;]+)', s_text, re.IGNORECASE)
            bg_m = re.search(r'(?:^|;)\s*background(?:-color)?:\s*([^;]+)', s_text, re.IGNORECASE)
            if fg_m and bg_m:
                fg_col = parse_css_color(fg_m.group(1))
                bg_col = parse_css_color(bg_m.group(1))
                if fg_col and bg_col:
                    ratio = calc_contrast_ratio(fg_col, bg_col)
                    if ratio < self.min_contrast:
                        findings.append({
                            "id": "low-contrast-text",
                            "severity": "FAIL",
                            "message": f"Color contrast ratio {ratio:.2f}:1 fails WCAG AA minimum ({self.min_contrast}:1).",
                            "snippet": sm.group(0)[:80]
                        })

        fails = [f for f in findings if f["severity"] == "FAIL"]
        warns = [f for f in findings if f["severity"] == "WARN"]

        return {
            "file": filename,
            "passed": len(fails) == 0,
            "fail_count": len(fails),
            "warn_count": len(warns),
            "findings": findings
        }

    def audit_file(self, file_path: str) -> Dict[str, Any]:
        if not os.path.exists(file_path):
            return {
                "file": file_path,
                "passed": False,
                "error": f"File not found: {file_path}",
                "findings": []
            }
        try:
            with open(file_path, "r", encoding="utf-8", errors="ignore") as f:
                content = f.read()
            return self.audit_html_content(content, filename=file_path)
        except Exception as e:
            return {
                "file": file_path,
                "passed": False,
                "error": str(e),
                "findings": []
            }

def main():
    parser = argparse.ArgumentParser(description="Mechanical layout and UI quality gate checker.")
    parser.add_argument("paths", nargs="*", help="HTML files or directories to audit.")
    parser.add_argument("--json", action="store_true", help="Output JSON format.")
    args = parser.parse_args()

    gate = MechanicalUIGate()
    target_files = []

    if not args.paths:
        # Default scan in reports/ or templates/
        for root in ["reports", "templates"]:
            if os.path.exists(root):
                for dirpath, _, files in os.walk(root):
                    for f in files:
                        if f.endswith(".html"):
                            target_files.append(os.path.join(dirpath, f))
    else:
        for p in args.paths:
            if os.path.isdir(p):
                for dirpath, _, files in os.walk(p):
                    for f in files:
                        if f.endswith(".html"):
                            target_files.append(os.path.join(dirpath, f))
            elif os.path.isfile(p):
                target_files.append(p)

    if not target_files:
        print("[MECHANICAL UI GATE] No HTML files provided or found. Exiting clean.", file=sys.stderr)
        sys.exit(0)

    results = [gate.audit_file(f) for f in target_files]
    total_fails = sum(r.get("fail_count", 0) for r in results)
    total_warns = sum(r.get("warn_count", 0) for r in results)
    all_passed = total_fails == 0

    if args.json:
        print(json.dumps({
            "overall_passed": all_passed,
            "total_files": len(results),
            "total_fails": total_fails,
            "total_warns": total_warns,
            "results": results
        }, indent=2))
    else:
        status_sym = "✅ PASS" if all_passed else "❌ FAIL"
        print(f"[MECHANICAL UI GATE] {status_sym} — Checked {len(results)} files | Fails: {total_fails} | Warnings: {total_warns}")
        for r in results:
            if not r["passed"] or r.get("warn_count", 0) > 0:
                print(f"  File: {r['file']}")
                for f in r.get("findings", []):
                    print(f"    - [{f['severity']}] {f['id']}: {f['message']}")

    if not all_passed:
        sys.exit(1)

if __name__ == "__main__":
    main()
