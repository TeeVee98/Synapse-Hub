#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
tools/generate_tc_from_story.py — Large Action Model (LAM) Script Generator
Inspired by LaVague: Converts natural language user stories into Clean POM Groovy test scripts.
Compatible with Windows, macOS, and Linux.
"""

import sys
import os
import re
import argparse

PAGE_MAP = {
    "login": "LoginPage",
    "common": "CommonCategoryPage",
    "commoncategory": "CommonCategoryPage",
    "industry": "IndustryCategoryPage",
    "industrycategory": "IndustryCategoryPage",
    "mining": "DataMiningPage",
    "datamining": "DataMiningPage",
    "user": "UserAdminPage",
    "useradmin": "UserAdminPage",
    "planning": "PlanningPage",
    "report": "ReportPage",
    "fluctuation": "MiningFluctuationPage",
}

def generate_script(story, module_name="CommonCategoryPage", tc_name="TC_AutoGenerated"):
    # Normalize module name
    mod_clean = module_name.lower().replace("page", "").replace("_", "")
    target_page = PAGE_MAP.get(mod_clean, "CommonCategoryPage")

    # Detect action intent from story keywords
    story_lower = story.lower()
    is_delete = any(k in story_lower for k in ["xóa", "xoa", "delete", "remove"])
    is_edit = any(k in story_lower for k in ["sửa", "sua", "chỉnh sửa", "chinh sua", "edit", "update"])
    is_search = any(k in story_lower for k in ["tìm", "tim", "tìm kiếm", "tim kiem", "search", "filter"])
    is_add = not (is_delete or is_edit or is_search) or any(k in story_lower for k in ["thêm", "them", "tạo mới", "tao moi", "add", "create"])

    lines = []
    lines.append("// ===========================================================================")
    lines.append(f"// Test Case: {tc_name}")
    lines.append(f"// Requirement: {story}")
    lines.append("// Architecture: Clean POM & Flat Architecture (Generated by LaVague LAM Engine)")
    lines.append("// ===========================================================================")
    lines.append("")
    lines.append("import dmit.pages.LoginPage")
    lines.append(f"import dmit.pages.{target_page}")
    lines.append("")
    lines.append("// 1. Đảm bảo trạng thái đăng nhập hệ thống")
    lines.append("LoginPage.ensureLoggedIn()")
    lines.append("")
    lines.append("// 2. Khởi tạo dữ liệu kiểm thử động (Idempotent Test Data)")
    lines.append('String uniqueCode = "AUTO_" + System.currentTimeMillis()')
    lines.append('String testName = "Dữ liệu kiểm thử " + uniqueCode')
    lines.append("")

    if is_add:
        lines.append("// 3. Thực thi kịch bản thêm mới dữ liệu")
        if target_page == "DataMiningPage":
            lines.append("DataMiningPage.goToDataMining()")
            lines.append('DataMiningPage.selectLayer("Cụm công nghiệp")')
            lines.append("DataMiningPage.drawPolygonOnCanvas()")
            lines.append('DataMiningPage.fillDynamicForm("Cụm công nghiệp", uniqueCode, testName)')
            lines.append("DataMiningPage.confirmAddForm()")
            lines.append("DataMiningPage.verifyMiningSuccess(uniqueCode)")
        else:
            lines.append(f"{target_page}.openCreateModal()")
            lines.append(f"{target_page}.fillCreateForm(uniqueCode, testName)")
            lines.append(f"{target_page}.confirmCreate()")
            lines.append(f"{target_page}.verifyCreateSuccess(uniqueCode)")

    elif is_edit:
        lines.append("// 3. Thực thi kịch bản chỉnh sửa dữ liệu")
        lines.append('String updatedName = testName + " [Cập nhật]"')
        if target_page == "DataMiningPage":
            lines.append("DataMiningPage.goToDataMining()")
            lines.append('DataMiningPage.selectLayer("Cụm công nghiệp")')
            lines.append("DataMiningPage.searchAndSelectRecord('Cụm công nghiệp', uniqueCode)")
            lines.append("DataMiningPage.editDataRecord('Cụm công nghiệp', updatedName)")
            lines.append("DataMiningPage.verifyRecordUpdated(updatedName)")
        else:
            lines.append(f"{target_page}.searchKeyword(uniqueCode)")
            lines.append(f"{target_page}.openEditFirstRow()")
            lines.append(f"{target_page}.updateName(updatedName)")
            lines.append(f"{target_page}.confirmEdit()")
            lines.append(f"{target_page}.verifyEditSuccess(updatedName)")

    elif is_delete:
        lines.append("// 3. Thực thi kịch bản xóa dữ liệu")
        if target_page == "DataMiningPage":
            lines.append("DataMiningPage.goToDataMining()")
            lines.append('DataMiningPage.selectLayer("Cụm công nghiệp")')
            lines.append("DataMiningPage.searchAndSelectRecord('Cụm công nghiệp', uniqueCode)")
            lines.append("DataMiningPage.deleteRecordFromPopup()")
            lines.append("DataMiningPage.verifyDeletedRecordNotFound(uniqueCode)")
        else:
            lines.append(f"{target_page}.searchKeyword(uniqueCode)")
            lines.append(f"{target_page}.clickDeleteFirstRow()")
            lines.append(f"{target_page}.confirmDeleteDialog()")
            lines.append(f"{target_page}.verifyDeleteSuccess(uniqueCode)")

    elif is_search:
        lines.append("// 3. Thực thi kịch bản tìm kiếm và lọc dữ liệu")
        if target_page == "DataMiningPage":
            lines.append("DataMiningPage.goToDataMining()")
            lines.append('DataMiningPage.selectLayer("Cụm công nghiệp")')
            lines.append("DataMiningPage.searchByMapLayer(uniqueCode, 'Cụm công nghiệp')")
            lines.append("DataMiningPage.verifySearchSuccess(uniqueCode)")
        else:
            lines.append(f"{target_page}.searchKeyword(uniqueCode)")
            lines.append(f"{target_page}.verifySearchResultFound(uniqueCode)")

    return "\n".join(lines)

def main():
    parser = argparse.ArgumentParser(description="Generate Clean POM Groovy automation script from natural language user story.")
    parser.add_argument("--story", "-s", required=True, help="Natural language description of the test scenario / user story.")
    parser.add_argument("--module", "-m", default="CommonCategory", help="Target module / Page Class (e.g. CommonCategory, DataMining, UserAdmin).")
    parser.add_argument("--name", "-n", default="TC_AutoGenerated", help="Name of the generated Test Case.")
    parser.add_argument("--output", "-o", help="File path to write the generated script.")
    args = parser.parse_args()

    script_content = generate_script(args.story, args.module, args.name)

    if args.output:
        os.makedirs(os.path.dirname(os.path.abspath(args.output)), exist_ok=True)
        with open(args.output, "w", encoding="utf-8") as fp:
            fp.write(script_content)
        print(f"✅ Clean POM script successfully generated to: {args.output}")
    else:
        print(script_content)

if __name__ == "__main__":
    main()
