#!/usr/bin/env python3
"""
ODP AI Documentation & Artifact Linter (Anti-Drift Guard v1.0)
---------------------------------------------------------------
Automatically cross-references AI skills, agent instructions, and markdown
documents against the actual repository files, classes, methods, and test cases.

Checks:
  1. Page Class references: Matches against Keywords/odp/pages/*.groovy.
  2. Test Suite references: Matches against Test Suites/*.ts.
  3. Tool script references: Matches against tools/* (memory_cache.db is
     runtime-generated by cache_resolver.py and exempted).
  4. Test Case references: Validates TC_01..TC_75 numeric range against
     Test Cases/*.tc.
  5. Method call references: Matches Helper/Page.method() against real
     Groovy method declarations.

Legacy root docs written before this guard existed (AGENTS.md, README.md,
HDSD.md, ONBOARDING.md, POM_REFACTORING_PLAN.md) are linted in LIGHT mode
(Page Classes, Suites, Tools only — no method/TC validation) so historical
wording does not block CI. New documents (.agents/**, PROJECT_STATE.md,
KNOWN_ISSUES.md, CICD_GUIDE.md, FUTURE_PROOF_5YR.md, AI_REPLICATION_GUIDE.md)
are linted in FULL mode. See KNOWN_ISSUES.md technical debt for legacy drift.

Prevents AI agents from hallucinating nonexistent PageClasses, suites, tools,
methods, or test cases.
"""

import os
import sys
import glob
import re

MAX_TC_ID = 75

GENERIC_PAGES = {
    "WebPage", "CurrentPage", "LandingPage", "GitHubPage", "SamplePage",
    "BasePage", "Page", "SinglePage", "MultiPage", "PomPatterns", "ExamplePage"
}

# Legacy docs: light lint only (no method/TC validation)
LEGACY_ROOT_DOCS = {
    "AGENTS.md", "README.md", "HDSD.md", "ONBOARDING.md", "POM_REFACTORING_PLAN.md",
}

# Runtime-generated artifacts (created on first run, not committed)
RUNTIME_TOOLS = {"memory_cache.db"}

def extract_groovy_methods(file_path):
    """Trích xuất danh sách các phương thức public/static chuẩn từ file Groovy."""
    methods = set()
    if not os.path.exists(file_path):
        return methods
    try:
        with open(file_path, "r", encoding="utf-8", errors="ignore") as fp:
            lines = fp.readlines()
        method_pattern = re.compile(
            r'^\s*(?:@\w+\s+)*(?:public|protected|private)?\s*(?:static\s+)?(?:final\s+)?'
            r'(?:void|def|String|int|boolean|Set[^\s]*|List[^\s]*|Map[^\s]*|File|TestObject|WebDriver|[A-Za-z0-9_<>\[\]]+)\s+([a-z][a-zA-Z0-9_]*)\s*\('
        )
        for line in lines:
            stripped = line.strip()
            if stripped.startswith("//") or stripped.startswith("*"):
                continue
            m = method_pattern.search(line)
            if m:
                mname = m.group(1)
                if mname not in {"if", "for", "while", "switch", "catch"}:
                    methods.add(mname)
    except Exception:
        pass
    return methods

def get_actual_entities(repo_root):
    pages_dir = os.path.join(repo_root, "Keywords", "odp", "pages")
    common_dir = os.path.join(repo_root, "Keywords", "odp", "common")
    suites_dir = os.path.join(repo_root, "Test Suites")
    cases_dir = os.path.join(repo_root, "Test Cases")
    tools_dir = os.path.join(repo_root, "tools")

    actual_pages = set()
    class_methods = {}

    if os.path.isdir(pages_dir):
        for f in os.listdir(pages_dir):
            if f.endswith(".groovy"):
                pname = f[:-7]
                actual_pages.add(pname)
                class_methods[pname] = extract_groovy_methods(os.path.join(pages_dir, f))

    if os.path.isdir(common_dir):
        for f in os.listdir(common_dir):
            if f.endswith(".groovy"):
                hname = f[:-7]
                actual_pages.add(hname)
                class_methods[hname] = extract_groovy_methods(os.path.join(common_dir, f))

    actual_suites = set()
    if os.path.isdir(suites_dir):
        for f in os.listdir(suites_dir):
            if f.endswith(".ts"):
                actual_suites.add(f[:-3])

    actual_cases = set()
    actual_tc_ids = set()
    tc_num_pattern = re.compile(r'TC\s?(\d{1,2})')
    if os.path.isdir(cases_dir):
        for f in os.listdir(cases_dir):
            if f.endswith(".tc"):
                base_name = f[:-3]
                actual_cases.add(base_name)
                for m in tc_num_pattern.finditer(base_name):
                    num = int(m.group(1))
                    if 1 <= num <= MAX_TC_ID:
                        actual_tc_ids.add(num)

    actual_tools = set()
    if os.path.isdir(tools_dir):
        actual_tools = set(os.listdir(tools_dir))

    return actual_pages, actual_suites, actual_cases, actual_tc_ids, actual_tools, class_methods

def find_doc_files(repo_root):
    md_patterns = [
        os.path.join(repo_root, ".agents", "**", "*.md"),
        os.path.join(repo_root, "*.md"),
    ]
    doc_files = []
    for pattern in md_patterns:
        for f in glob.glob(pattern, recursive=True):
            rel = os.path.relpath(f, repo_root).replace("\\", "/")
            if "node_modules" in rel or ".git" in rel:
                continue
            doc_files.append(rel)
    return sorted(doc_files)

def lint_docs(repo_root):
    actual_pages, actual_suites, actual_cases, actual_tc_ids, actual_tools, class_methods = get_actual_entities(repo_root)
    doc_files = find_doc_files(repo_root)

    page_pattern = re.compile(r'\b([A-Z][A-Za-z0-9]+Page)\b')
    suite_pattern = re.compile(r'Test Suites/([A-Za-z0-9_]+)')
    tool_pattern = re.compile(r'\btools/([a-zA-Z0-9_\-\.]+\.(?:py|sh|ps1|bat|js|json|db))\b')
    tc_id_pattern = re.compile(r'\bTC[_\s]?(\d{1,2})\b')
    tc_path_pattern = re.compile(r'Test Cases/([A-Za-z0-9_ \-\.]+?)(?:\.tc)?["\s\)]')
    method_pattern = re.compile(r'\b(BasePage|DataHelper|ProfileHelper|Select2Helper|TelegramHelper|[A-Z][a-zA-Z0-9]+Page)\.([a-z][a-zA-Z0-9_]+)\s*\(')

    errors = []
    warnings = []

    for doc in doc_files:
        full_path = os.path.join(repo_root, doc)
        is_light_mode = os.path.basename(doc) in LEGACY_ROOT_DOCS
        try:
            with open(full_path, "r", encoding="utf-8", errors="ignore") as fp:
                lines = fp.readlines()
        except Exception as e:
            errors.append(f"Cannot read {doc}: {e}")
            continue

        for line_no, line in enumerate(lines, 1):
            # 1. Page Class Lint (both modes)
            for m in page_pattern.finditer(line):
                pname = m.group(1)
                if pname not in actual_pages and pname not in GENERIC_PAGES:
                    errors.append(f"[{doc}:{line_no}] Non-existent Page Class referenced: '{pname}' (Must be one of {sorted(actual_pages)})")

            # 2. Test Suite Lint (both modes)
            for m in suite_pattern.finditer(line):
                sname = m.group(1)
                if "xxx" in sname.lower() or "example" in sname.lower():
                    continue
                if sname not in actual_suites:
                    errors.append(f"[{doc}:{line_no}] Non-existent Test Suite referenced: '{sname}'")

            # 3. Tool Script Lint (both modes)
            for m in tool_pattern.finditer(line):
                tname = m.group(1)
                if tname in RUNTIME_TOOLS:
                    continue
                if tname not in actual_tools:
                    errors.append(f"[{doc}:{line_no}] Non-existent tool script referenced: 'tools/{tname}'")

            # 4-5. Only for FULL mode (new docs)
            if not is_light_mode:
                # 4a. Validate TC numeric range (1..75)
                for m in tc_id_pattern.finditer(line):
                    num = int(m.group(1))
                    if num < 1 or num > MAX_TC_ID:
                        errors.append(f"[{doc}:{line_no}] Out-of-range Test Case ID referenced: 'TC_{m.group(1)}' (Valid range: TC_01 to TC_{MAX_TC_ID})")

                # 4b. Validate full Test Cases/... paths (prefix match)
                for m in tc_path_pattern.finditer(line):
                    tcname = m.group(1).strip()
                    if "xxx" in tcname.lower() or "*" in tcname or "example" in tcname.lower():
                        continue
                    if tcname.endswith(".tc"):
                        tcname = tcname[:-3]
                    matching = [c for c in actual_cases if c.startswith(tcname)]
                    if not matching:
                        errors.append(f"[{doc}:{line_no}] Non-existent Test Case path referenced: 'Test Cases/{tcname}'")

                # 5. Method Call Lint (Cross-checks Class.method() against Groovy declarations)
                for m in method_pattern.finditer(line):
                    cname = m.group(1)
                    mname = m.group(2)
                    if "xxx" in mname.lower() or "example" in mname.lower():
                        continue
                    if cname in class_methods:
                        valid_methods = class_methods[cname]
                        # Also include inherited BasePage methods if it's a Page class
                        if cname != "BasePage" and "BasePage" in class_methods:
                            valid_methods = valid_methods.union(class_methods["BasePage"])

                        if mname not in valid_methods:
                            errors.append(f"[{doc}:{line_no}] Non-existent method referenced: '{cname}.{mname}()' (Class '{cname}' does not define this method)")

    return errors, warnings

def main():
    repo_root = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
    print(f"🔍 Running ODP AI Docs & Artifacts Linter v1.0 on repository: {os.path.basename(repo_root)}")
    errors, warnings = lint_docs(repo_root)

    if warnings:
        print(f"\n⚠️  {len(warnings)} Warnings:")
        for w in warnings:
            print(f"   - {w}")

    if errors:
        print(f"\n❌ {len(errors)} Lint Errors Found (Documentation Drift / Hallucination):")
        for e in errors:
            print(f"   - {e}")
        print("\n🚫 Verification failed: Please align documentation with real disk entities.")
        sys.exit(1)
    else:
        print("✅ [AI DOCS LINTER PASSED] All PageClasses, Suites, Tools, TestCases, and Method calls exist on disk.")
        sys.exit(0)

if __name__ == "__main__":
    main()
